    @Override
    public void setupAnim(CrimsonKnightRenderState state) {
        // 每帧先复位，防止角度累加漂移（采样器内部也会复位，这里保证非动画阶段也归位）
        switch (state.crimsonPhase) {
            case ATTACK -> CrimsonPosePlayer.apply("attack", state.crimsonAnimSeconds, namedParts);
            case DYING, DEAD -> CrimsonPosePlayer.apply("death", state.crimsonAnimSeconds, namedParts);
            default -> {
                for (ModelPart part : namedParts.values()) {
                    part.resetPose();
                }
            }
        }
    }

